"""amdgpu-wddm: write or check bc250_env_sites.h, the table of every read of the BC-250 environment helper.

    python3 bc250_env_sites.py <mesa source root> [--check]

The table holds one entry for each distinct read of the tree (the form, the name and the default) of the helper
macros of util/bc250_env.h. bc250_env_test.c expands each entry in both flavours and compares the values. --check
fails when the table in the tree is not the one that the sources give, so a new read cannot miss the test.
"""
import re
import sys
from pathlib import Path

FORMS = ('BC250_ENV_BOOL_P', 'BC250_ENV_BOOL', 'BC250_ENV_NUM_P', 'BC250_ENV_NUM', 'BC250_ENV_STR_P',
         'BC250_ENV_STR', 'BC250_GETENV_P', 'BC250_GETENV', 'BC250_OS_OPTION', 'BC250_GET_ONCE_BOOL_OPTION_P',
         'BC250_GET_ONCE_BOOL_OPTION', 'BC250_GET_ONCE_OPTION')
USE = re.compile(r'\b(' + '|'.join(FORMS) + r')\s*\(')
SKIP = {'src/util/bc250_env.h', 'src/util/tests/bc250_env_sites.h', 'src/util/tests/bc250_env_test.c'}


def args_of(text, i):
    depth, k, start = 0, i, i + 1
    out = []
    while k < len(text):
        c = text[k]
        if c == '"':
            k += 1
            while text[k] != '"':
                k += 2 if text[k] == '\\' else 1
        elif c == '(':
            depth += 1
        elif c == ')':
            depth -= 1
            if depth == 0:
                out.append(text[start:k])
                return [' '.join(a.split()) for a in out]
        elif c == ',' and depth == 1:
            out.append(text[start:k])
            start = k + 1
        k += 1
    raise ValueError('unclosed call')


def defines(root):
    """The object-like #define values of the tree, for a default that names a macro."""
    out = {}
    for p in (root / 'src' / 'amd').rglob('*.[ch]'):
        for m in re.finditer(r'^#define\s+([A-Z0-9_]+)\s+([()0-9xXa-fA-FuUlL<> +*-]*[0-9][()0-9xXa-fA-FuUlL<> +*-]*?)\s*(?:/\*.*)?$',
                             p.read_text(encoding='utf-8', errors='replace'), re.M):
            out[m.group(1)] = m.group(2)
    return out


def table(root):
    sites = {}
    for p in sorted((root / 'src').rglob('*')):
        rel = p.relative_to(root).as_posix()
        if p.suffix not in ('.c', '.h', '.cpp') or rel in SKIP:
            continue
        text = p.read_text(encoding='utf-8', errors='replace')
        if 'BC250_' not in text:
            continue
        for m in USE.finditer(text):
            line_start = text.rfind('\n', 0, m.start()) + 1
            if text[line_start:m.start()].lstrip().startswith(('#define', '*', '/*', '//')):
                continue
            a = args_of(text, m.end() - 1)
            form = m.group(1)
            if form.startswith('BC250_GET_ONCE'):
                a = a[1:]
            sites.setdefault((form, a[0], a[1] if len(a) > 1 else ''), []).append(
                f'{rel}:{text.count(chr(10), 0, m.start()) + 1}')
    return sites


def render(root):
    macros = defines(root)
    lines = ['/* SPDX-License-Identifier: MIT */',
             '/* Generated by bc250_env_sites.py from the reads of the tree: do not edit. One entry per distinct read',
             ' * (form, name, default), with the first site that reads it. */']
    for (form, name, dflt), where in sorted(table(root).items()):
        value = macros.get(dflt, dflt) if re.fullmatch(r'[A-Z][A-Z0-9_]+', dflt or '_') and dflt not in (
            'NULL',) else dflt
        if re.fullmatch(r'[A-Z][A-Z0-9_]+', value or '_') and value != 'NULL':
            raise SystemExit(f'{where[0]}: the default {dflt} of {name} is a macro this script cannot resolve')
        lines.append(f'BC250_SITE({form}, {name}, {value or "_"}, "{where[0]}", {len(where)})')
    return '\n'.join(lines) + '\n'


def main():
    root = Path(sys.argv[1])
    out = root / 'src/util/tests/bc250_env_sites.h'
    text = render(root)
    if '--check' in sys.argv:
        if not out.is_file() or out.read_text(encoding='utf-8').replace('\r\n', '\n') != text:
            print(f'{out} is not the table of the tree: run bc250_env_sites.py {root}')
            return 1
        print(f'bc250_env_sites.h: {text.count("BC250_SITE(")} reads, up to date')
        return 0
    out.write_text(text, encoding='utf-8', newline='\n')
    print(f'wrote {out}: {text.count("BC250_SITE(")} reads')
    return 0


if __name__ == '__main__':
    sys.exit(main())
